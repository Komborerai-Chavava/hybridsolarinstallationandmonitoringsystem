FONT_FAMILY = "Times New Roman"
BG = "#ffffff"
PANEL_BG = "#f2f2f2"
FG = "#000000"
BORDER = "#000000"

TICK_MS = 600            # simulated-time step, in milliseconds of real time
CREDIT_FACTOR_DOMESTIC = 0.8   # ZESA domestic net-metering credit factor, kWh credited per kWh exported
HISTORY_LEN = 120        # how many readings are kept for the rolling chart
FORECAST_WINDOW = 6      # how many recent readings the forecast model looks at


def now_str():
    return datetime.datetime.now().strftime("%H:%M:%S")


class SolarModel:
    """Generates a synthetic day-cycle of solar output plus a fixed
    household demand, standing in for the CT clamp and voltage sensor
    readings the real device would take. Cloud dips and faults can be
    injected manually to demonstrate the forecasting and alerting
    logic on demand, rather than waiting for a randomly timed event."""

    def __init__(self):
        self.t = 0
        self.demand = 55.0          # simulated constant household load, in "units"
        self.cloud_ticks_left = 0
        self.fault = False
        self.history = []           # list of (t, solar_output)

    def inject_cloud(self, duration_ticks=14):
        self.cloud_ticks_left = duration_ticks

    def toggle_fault(self, value):
        self.fault = value

    def step(self):
        self.t += 1
        # base diurnal curve: 0 at "night", peaking at simulated midday
        cycle = max(0.0, math.sin((self.t % 200) / 200 * math.pi))
        base = cycle * 100.0
        noise = random.uniform(-3, 3)
        output = max(0.0, base + noise)

        if self.cloud_ticks_left > 0:
            output *= 0.25  # heavy attenuation during a cloud event
            self.cloud_ticks_left -= 1

        if self.fault:
            output = 0.0

        self.history.append((self.t, output))
        if len(self.history) > HISTORY_LEN:
            self.history.pop(0)
        return output


class ForecastEngine:
    """Looks at the last few readings and flags a likely dip before
    output has actually collapsed, per Methodology 3. This is a
    deliberately simple trend check, not a machine-learning model —
    it is meant to demonstrate the behaviour, not to be production
    forecasting logic."""

    def __init__(self, window=FORECAST_WINDOW):
        self.window = window

    def check(self, history):
        if len(history) < self.window:
            return False
        recent = [v for _, v in history[-self.window:]]
        # simple slope check: is generation falling steadily and fast?
        diffs = [recent[i + 1] - recent[i] for i in range(len(recent) - 1)]
        avg_slope = sum(diffs) / len(diffs)
        return avg_slope < -4.0 and recent[-1] < recent[0]


class BillingLedger:
    """Independently accumulates exported energy, per Methodology 5,
    so it can later be compared against whatever figure ZESA actually
    credits the customer — entered manually here, since no public
    ZETDC interface for that figure was found during the literature
    review."""

    def __init__(self):
        self.logged_export_units = 0.0

    def add_export(self, export_amount, dt_hours):
        if export_amount > 0:
            self.logged_export_units += export_amount * dt_hours

    def verify(self, zesa_credited_units, tolerance=0.05):
        expected_credit = self.logged_export_units * CREDIT_FACTOR_DOMESTIC
        if expected_credit == 0:
            variance_pct = 0.0
        else:
            variance_pct = abs(expected_credit - zesa_credited_units) / expected_credit
        flagged = variance_pct > tolerance
        return expected_credit, variance_pct, flagged


class InstallerDashboard:
    """Holds illustrative demo rows for other clients, so the
    multi-client dashboard in Methodology has something to show
    beyond the one live-simulated installation. These other rows are
    static/randomised demonstration data only, not live readings."""

    DEMO_NAMES = ["Sengwayo Farm", "Chegutu High School", "Riverside Butchery", "Chegutu hotel"]

    def __init__(self):
        self.rows = []
        for name in self.DEMO_NAMES:
            self.rows.append({
                "name": name,
                "status": random.choice(["SOLAR", "MIXED", "GRID"]),
                "last_alert": "-",
                "variance_pct": round(random.uniform(0, 4), 1),
            })

    def maybe_update(self):
        if random.random() < 0.06:
            row = random.choice(self.rows)
            row["status"] = random.choice(["SOLAR", "MIXED", "GRID", "FAULT"])
            if row["status"] == "FAULT":
                row["last_alert"] = now_str() + "  Fault detected"


class StatusIndicator(tk.Canvas):
    """Draws the colour-free status indicator: shape and fill pattern
    encode state rather than colour, per the black-and-white brief."""

    SIZE = 130

    def __init__(self, master):
        super().__init__(master, width=self.SIZE, height=self.SIZE, bg=BG, highlightthickness=0)
        self.state = "GRID"
        self.blink_on = True
        self.draw()

    def set_state(self, state):
        self.state = state
        self.draw()

    def blink(self):
        self.blink_on = not self.blink_on
        if self.state == "FAULT":
            self.draw()

    def draw(self):
        self.delete("all")
        s = self.SIZE
        pad = 8
        if self.state == "SOLAR":
            self.create_oval(pad, pad, s - pad, s - pad, fill="#000000", outline="#000000", width=2)
            self.create_text(s / 2, s / 2, text="SOLAR", fill="#ffffff", font=(FONT_FAMILY, 11, "bold"))
        elif self.state == "MIXED":
            self.create_oval(pad, pad, s - pad, s - pad, fill="#ffffff", outline="#000000", width=2)
            self.create_arc(pad, pad, s - pad, s - pad, start=90, extent=180, fill="#000000", outline="#000000")
            self.create_text(s / 2, s - 18, text="MIXED", fill="#000000", font=(FONT_FAMILY, 11, "bold"))
        elif self.state == "GRID":
            self.create_oval(pad, pad, s - pad, s - pad, fill="#ffffff", outline="#000000", width=4)
            self.create_text(s / 2, s / 2, text="GRID", fill="#000000", font=(FONT_FAMILY, 11, "bold"))
        else:  # FAULT
            fill = "#000000" if self.blink_on else "#ffffff"
            textcol = "#ffffff" if self.blink_on else "#000000"
            self.create_oval(pad, pad, s - pad, s - pad, fill=fill, outline="#000000", width=4)
            self.create_line(pad + 10, pad + 10, s - pad - 10, s - pad - 10, fill=textcol, width=4)
            self.create_line(s - pad - 10, pad + 10, pad + 10, s - pad - 10, fill=textcol, width=4)
            self.create_text(s / 2, s - 6, text="FAULT", fill="#000000", font=(FONT_FAMILY, 10, "bold"))


