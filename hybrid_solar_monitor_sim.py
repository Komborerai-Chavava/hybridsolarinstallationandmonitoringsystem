"""
Hybrid Solar Installation and Monitoring System — Software Simulation
=======================================================================

This is a desktop (Tkinter) simulation of the system described in the
project's Methodology section. No physical hardware exists yet — no
CT clamp, no voltage sensor, no relay, no GSM module, no RGB
indicator — so every "reading" in this program is generated by a
simple synthetic day-cycle model, not measured from a real
installation. It exists purely to demonstrate, on screen, how the
six functions in the Methodology are meant to behave and interact:

    1. Baseline status display               (Methodology 1)
    2. Load balancing / export control       (Methodology 2)
    3. Predictive generation-dip forecasting (Methodology 3)
    4. Automated dual alerting               (Methodology 4)
    5. Billing verification                  (Methodology 5)
    6. Multi-client installer dashboard      (Methodology 6)

The interface is deliberately kept in black, white and grey — no
colour is used to signal state. Status is instead shown through
shape, fill pattern and bold text labels, so the same distinctions
would still be readable on a black-and-white printout.

Run with:  python hybrid_solar_monitor_sim.py
Requires:  Python 3.9+, matplotlib (pip install matplotlib)
           Tkinter ships with most desktop Python installs; on some
           Linux distributions it must be installed separately, e.g.
           sudo apt install python3-tk
"""

import random
import math
import datetime
